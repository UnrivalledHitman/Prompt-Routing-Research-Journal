"""Build the FGCS submission package from the LaTeX source.

    python build_submission.py

Writes submission/ and FGCS_submission.zip next to this file, holding every
file the journal's guide for authors asks for, and stops with an error if a
hard limit is broken: the 18-page cap, the 250-word abstract, or the
highlights' 3-5 bullets of at most 85 characters.

Editorial Manager compiles LaTeX with every uploaded file in one directory,
so the manuscript is flattened into a single .tex with the sections, tables
and bibliography inlined and the figures referenced by bare file name.

Needs pdflatex and bibtex, and pandoc for the two Word files. Set PANDOC to
pandoc's path if it is not on PATH.
"""
import glob
import os
import pathlib
import re
import shutil
import subprocess
import sys
import zipfile

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "submission"
ZIP = HERE / "FGCS_submission.zip"
PAGE_LIMIT = 18
ABSTRACT_LIMIT = 250
HIGHLIGHT_CHARS = 85
VITAE_WORDS = 100
FIGURES = [f"Figure_{n}.pdf" for n in range(1, 5)]
# Author photographs are kept out of version control in photos/.
PHOTOS = ["Photo_1.jpg", "Photo_2.jpg"]
BUILD_JUNK = (".aux", ".log", ".out", ".spl", ".blg", ".bbl")


def fail(msg):
    sys.exit(f"build_submission: {msg}")


def run(cmd, cwd):
    subprocess.run(cmd, cwd=cwd, stdout=subprocess.DEVNULL,
                   stderr=subprocess.DEVNULL, check=False)


def is_miktex():
    out = subprocess.run(["pdflatex", "--version"], capture_output=True, text=True)
    return "MiKTeX" in out.stdout


# MiKTeX installs missing packages on the fly; never let a build download.
NO_INSTALL = ["--disable-installer"] if is_miktex() else []


def latex(name, cwd, bib=False):
    """Compile name.tex in cwd and return its log text."""
    tex = ["pdflatex", *NO_INSTALL, "--interaction=nonstopmode", f"{name}.tex"]
    run(tex, cwd)
    if bib:
        run(["bibtex", name], cwd)
    run(tex, cwd)
    run(tex, cwd)
    return (cwd / f"{name}.log").read_text(encoding="utf-8", errors="replace")


def check_log(log, name):
    errors = re.findall(r"(?m)^! .*", log)
    undefined = re.findall(r"(?:Citation|Reference) `([^']+)'[^\n]*undefined", log)
    overfull = log.count("Overfull \\hbox")
    pages = re.search(rf"Output written on {name}\.pdf \((\d+) pages?", log)
    if errors:
        fail(f"{name}: LaTeX errors: {errors[:3]}")
    if undefined:
        fail(f"{name}: undefined references: {sorted(set(undefined))}")
    if not pages:
        fail(f"{name}: no PDF was written")
    if overfull:
        fail(f"{name}: {overfull} overfull box(es); something runs into the margin")
    return int(pages.group(1)), overfull


def inline_inputs(text, base):
    def repl(m):
        path = base / m.group(1)
        if path.suffix != ".tex":
            path = path.with_suffix(".tex")
        return inline_inputs(path.read_text(encoding="utf-8"), base)
    return re.sub(r"\\input\{([^}]+)\}", repl, text)


def flatten_manuscript():
    text = inline_inputs((HERE / "manuscript.tex").read_text(encoding="utf-8"), HERE)
    bbl = (HERE / "manuscript.bbl").read_text(encoding="utf-8")
    text = text.replace("\\bibliographystyle{elsarticle-num}\n", "")
    text = text.replace("\\bibliography{refs,refs-methods}", bbl.strip())
    text = re.sub(r"\\graphicspath\{\{[^}]*\}\}\n", "", text)
    text = re.sub(r"(?m)^[ \t]*%.*\n", "", text)
    header = ("% The escalation tax -- manuscript for Future Generation Computer\n"
              "% Systems. Single-file source generated by build_submission.py:\n"
              "% sections, tables and bibliography are inlined, and figures are\n"
              "% the separately uploaded Figure_1.pdf to Figure_4.pdf.\n")
    return header + text


def check_abstract(text):
    body = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", text, re.S).group(1)
    body = body.replace("{,}", ",")           # 3{,}612 is one word
    body = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?", " ", body)
    body = body.translate(str.maketrans("{}~$\\", "     "))
    words = [w for w in body.split() if any(c.isalnum() for c in w)]
    if len(words) > ABSTRACT_LIMIT:
        fail(f"abstract is {len(words)} words, limit {ABSTRACT_LIMIT}")
    return len(words)


def check_highlights():
    text = (HERE / "highlights.tex").read_text(encoding="utf-8")
    items = [" ".join(i.split()) for i in
             re.findall(r"\\item(.*?)(?=\\item|\\end\{itemize\})", text, re.S)]
    if not 3 <= len(items) <= 5:
        fail(f"{len(items)} highlights, need 3 to 5")
    long = [i for i in items if len(i) > HIGHLIGHT_CHARS]
    if long:
        fail(f"highlights over {HIGHLIGHT_CHARS} characters: {long}")
    return max(len(i) for i in items)


def check_vitae():
    text = (HERE / "author-biographies.tex").read_text(encoding="utf-8")
    counts = {}
    for name, bio in re.findall(r"\\textbf\{([^}]+)\}(.*?)(?=\\bigskip|\\end\{document\})",
                                text, re.S):
        if "[" in bio:
            fail(f"biography of {name} still has a placeholder")
        words = re.sub(r"\\[a-zA-Z]+|[{}\\]", " ", name + bio).split()
        counts[name] = len(words)
    over = {n: c for n, c in counts.items() if c > VITAE_WORDS}
    if over:
        fail(f"biographies over {VITAE_WORDS} words: {over}")
    return counts


def find_pandoc():
    candidates = [os.environ.get("PANDOC"), shutil.which("pandoc")]
    local = os.environ.get("LOCALAPPDATA", "")
    candidates += sorted(glob.glob(os.path.join(local, "Programs", "pandoc-*", "pandoc.exe")))
    for c in candidates:
        if c and pathlib.Path(c).exists():
            return c
    fail("pandoc not found; set PANDOC to its path")


def to_docx(pandoc, src, dest):
    subprocess.run([pandoc, str(src), "-f", "latex", "-t", "docx",
                    "-M", "lang=en-GB", "-o", str(dest)], check=True)


README = """FGCS submission package -- The escalation tax
==============================================

Upload to Editorial Manager as follows.

  manuscript.tex            Manuscript (LaTeX source). Single file, 18 pages
                            when compiled. Upload together with the four
                            figures, which it includes by file name.
  Figure_1.pdf ... _4.pdf   Figures, one file each, vector PDF with fonts
                            embedded.
  highlights.docx           Highlights (5 bullets, each <= 85 characters).
  Supplementary_material.pdf  Supplementary material (Tables S1-S8,
                            Figures S1-S6), cited from the manuscript.
  Author_biographies.docx   Vitae, <= 100 words per author.
  Photo_1.jpg, Photo_2.jpg  Passport-type photographs: Photo_1 is
                            Indrajeet Mondal, Photo_2 is Suseta Datta.
  manuscript.pdf            For checking only: the PDF this source builds.
                            Editorial Manager builds its own from the .tex.

Also required in the submission system, not as files:
  - the corresponding author's ORCID, 0009-0009-7966-2683
    (https://orcid.org/0009-0009-7966-2683), linked to the Editorial
    Manager profile. The record must be visible to Everyone and must hold
    some information, such as the Narula education entry, or the
    submission is rejected at the identity check;
  - the declarations (competing interests, generative AI, funding), which
    are already stated at the end of the manuscript.
"""


def main():
    pages, overfull = check_log(latex("manuscript", HERE, bib=True), "manuscript")
    if pages > PAGE_LIMIT:
        fail(f"manuscript is {pages} pages, limit {PAGE_LIMIT}")

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()

    flat = flatten_manuscript()
    words = check_abstract(flat)
    (OUT / "manuscript.tex").write_text(flat, encoding="utf-8")
    for fig in FIGURES:
        shutil.copy2(HERE / "figures" / fig, OUT / fig)

    # The flattened source must build on its own, as Editorial Manager will.
    flat_pages, flat_overfull = check_log(latex("manuscript", OUT), "manuscript")
    if flat_pages != pages:
        fail(f"flattened source builds to {flat_pages} pages, not {pages}")
    for junk in OUT.iterdir():
        if junk.suffix in BUILD_JUNK:
            junk.unlink()

    supp_pages, _ = check_log(latex("supplementary-material", HERE), "supplementary-material")
    shutil.copy2(HERE / "supplementary-material.pdf", OUT / "Supplementary_material.pdf")

    longest = check_highlights()
    vitae = check_vitae()
    pandoc = find_pandoc()
    to_docx(pandoc, HERE / "highlights.tex", OUT / "highlights.docx")
    to_docx(pandoc, HERE / "author-biographies.tex", OUT / "Author_biographies.docx")

    missing = [p for p in PHOTOS if not (HERE / "photos" / p).exists()]
    for p in PHOTOS:
        if p not in missing:
            shutil.copy2(HERE / "photos" / p, OUT / p)

    (OUT / "README.txt").write_text(README, encoding="utf-8")

    if ZIP.exists():
        ZIP.unlink()
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(OUT.iterdir()):
            z.write(f, f.name)

    print(f"manuscript: {pages} pages (limit {PAGE_LIMIT}), {overfull} overfull boxes; "
          f"flattened source builds identically")
    print(f"abstract: {words} words (limit {ABSTRACT_LIMIT}); "
          f"highlights: longest {longest} characters (limit {HIGHLIGHT_CHARS})")
    print(f"supplementary: {supp_pages} pages")
    print("vitae: " + ", ".join(f"{n} {c} words" for n, c in vitae.items())
          + f" (limit {VITAE_WORDS})")
    if missing:
        print(f"WARNING: photographs missing from photos/: {missing}")
    print(f"wrote {OUT.name}/ ({len(list(OUT.iterdir()))} files) and {ZIP.name}")


if __name__ == "__main__":
    main()
